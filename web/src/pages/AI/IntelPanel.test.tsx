import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { IntelCandidate } from '../../types/api';
import { cacheAccount, clearAccount } from '../../authProfile';
import IntelPanel from './IntelPanel';

const apiMocks = vi.hoisted(() => ({
  fetchIntelCandidates: vi.fn(),
  importIntelURL: vi.fn(),
  approveIntelCandidate: vi.fn(),
  rejectIntelCandidate: vi.fn(),
}));

vi.mock('react-i18next', () => ({
  initReactI18next: { type: '3rdParty', init: () => undefined },
  useTranslation: () => ({
    t: (key: string) => key,
    i18n: { language: 'en-US' },
  }),
}));

vi.mock('../../api/intel', () => ({
  fetchIntelCandidates: apiMocks.fetchIntelCandidates,
  importIntelURL: apiMocks.importIntelURL,
  approveIntelCandidate: apiMocks.approveIntelCandidate,
  rejectIntelCandidate: apiMocks.rejectIntelCandidate,
}));

const draftCandidate: IntelCandidate = {
  id: 'cand-1',
  item_id: 'item-1',
  site_id: 'site-a',
  rule_json: JSON.stringify({
    rule: {
      id: 'intel-php-marker-abc123',
      name: 'Intel CVE-2026-1234 php-marker',
      description: 'Generated by the deterministic intel compiler; class=php-marker; cves=CVE-2026-1234; review before enabling.',
      action: 'log',
      enabled: false,
    },
    scope: { site_id: 'site-a', path_prefix: '/upload' },
  }),
  action: 'log',
  state: 'draft',
  confidence: 0.97,
  provenance: {
    source_id: 'source-1',
    source_trust: 'vendor',
    item_id: 'item-1',
    extractor: 'advisory',
  },
  ttl: 86_400_000_000_000,
  created_at: '2026-10-20T00:00:00Z',
};

function renderPanel() {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false }, mutations: { retry: false } },
  });
  return render(
    <QueryClientProvider client={queryClient}>
      <IntelPanel />
    </QueryClientProvider>,
  );
}

describe('IntelPanel', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    sessionStorage.clear();
    cacheAccount({ username: 'alice', role: 'operator', scopes: ['read:protection', 'write:protection'] });
    apiMocks.fetchIntelCandidates.mockResolvedValue({ candidates: [], count: 0 });
  });

  it('stays hidden without an intel review scope and skips the list request', () => {
    clearAccount();
    cacheAccount({ username: 'alice', role: 'operator', scopes: ['read:ai'] });

    renderPanel();

    expect(screen.queryByText('ai.intelTitle')).toBeNull();
    expect(apiMocks.fetchIntelCandidates).not.toHaveBeenCalled();
  });

  it('renders the empty state and the default log-only notice', async () => {
    renderPanel();

    expect(await screen.findByText('ai.intelEmpty')).toBeTruthy();
    expect(screen.getByText('ai.intelReviewNotice')).toBeTruthy();
    expect(screen.getByText('ai.intelNoBlockDefault')).toBeTruthy();
    expect(apiMocks.fetchIntelCandidates).toHaveBeenCalledWith({});
  });

  it('lists candidates with state, action, confidence, CVE, and step', async () => {
    apiMocks.fetchIntelCandidates.mockResolvedValue({ candidates: [draftCandidate], count: 1 });

    renderPanel();

    expect(await screen.findByText('CVE-2026-1234')).toBeTruthy();
    expect(screen.getByText('php-marker')).toBeTruthy();
    expect(screen.getByText('97.0%')).toBeTruthy();
    expect(screen.getByText('ai.intelStateDraft')).toBeTruthy();
    expect(screen.getByText('securityActions.log')).toBeTruthy();
    expect(screen.getByText('site-a')).toBeTruthy();
    expect(screen.getByText('ai.intelCandidateCount')).toBeTruthy();
  });

  it('imports an advisory URL and rejects obviously unsafe input before the API', async () => {
    apiMocks.importIntelURL.mockResolvedValue({
      job_id: 'job-1',
      item: { id: 'item-1', source_id: 'source-1' },
      candidate: draftCandidate,
      impact: { verdict: 'needs-review' },
      candidates: [{ candidate: draftCandidate, impact: { verdict: 'needs-review' } }],
      item_created: true,
      candidate_created: true,
    });

    renderPanel();

    const importButton = screen.getByRole('button', { name: 'ai.intelImport' });
    fireEvent.change(screen.getByLabelText('ai.intelUrl'), { target: { value: 'javascript:alert(1)' } });
    fireEvent.change(screen.getByLabelText('ai.intelSiteID'), { target: { value: 'site-a' } });
    fireEvent.click(importButton);

    expect(await screen.findByText('ai.intelInvalidUrl')).toBeTruthy();
    expect(apiMocks.importIntelURL).not.toHaveBeenCalled();

    fireEvent.change(screen.getByLabelText('ai.intelUrl'), { target: { value: 'https://vendor.example/advisory/CVE-2026-1234' } });
    fireEvent.change(screen.getByLabelText('ai.intelPathPrefix'), { target: { value: '/upload' } });
    fireEvent.click(importButton);

    await waitFor(() => expect(apiMocks.importIntelURL).toHaveBeenCalledWith({
      url: 'https://vendor.example/advisory/CVE-2026-1234',
      site_id: 'site-a',
      path_prefix: '/upload',
    }));
    expect(screen.queryByText('ai.intelInvalidUrl')).toBeNull();
  });

  it('requires a typed approver name and the confirmation checkbox before approval', async () => {
    apiMocks.fetchIntelCandidates.mockResolvedValue({ candidates: [draftCandidate], count: 1 });
    apiMocks.approveIntelCandidate.mockResolvedValue({ candidate: { ...draftCandidate, state: 'shadow' } });

    renderPanel();

    fireEvent.click(await screen.findByRole('button', { name: 'ai.intelApproveFor' }));
    const confirmButton = screen.getByRole('button', { name: 'ai.intelConfirmApproval' });
    const approverInput = screen.getByLabelText('ai.intelApprovedBy');
    const checkbox = screen.getByRole('checkbox');

    expect((approverInput as HTMLInputElement).value).toBe('alice');
    expect((confirmButton as HTMLButtonElement).disabled).toBe(true);

    fireEvent.change(approverInput, { target: { value: '' } });
    fireEvent.click(checkbox);
    expect((confirmButton as HTMLButtonElement).disabled).toBe(true);
    expect(apiMocks.approveIntelCandidate).not.toHaveBeenCalled();

    fireEvent.change(approverInput, { target: { value: 'alice' } });
    expect((confirmButton as HTMLButtonElement).disabled).toBe(false);
    fireEvent.click(confirmButton);

    await waitFor(() => expect(apiMocks.approveIntelCandidate).toHaveBeenCalledWith('cand-1', {
      approved_by: 'alice',
      confirm: true,
      action: 'log',
    }));
  });

  it('shows a server rejection reason inside the approval form', async () => {
    apiMocks.fetchIntelCandidates.mockResolvedValue({ candidates: [draftCandidate], count: 1 });
    apiMocks.approveIntelCandidate.mockRejectedValue(new Error('impact assessment rejected this candidate (broadness exceeds policy)'));

    renderPanel();

    fireEvent.click(await screen.findByRole('button', { name: 'ai.intelApproveFor' }));
    fireEvent.click(screen.getByRole('checkbox'));
    fireEvent.click(screen.getByRole('button', { name: 'ai.intelConfirmApproval' }));

    const alert = await screen.findByRole('alert');
    expect(alert.textContent).toContain('impact assessment rejected this candidate (broadness exceeds policy)');
  });
});
